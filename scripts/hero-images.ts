/**
 * Builds the home-page hero photos from the originals in hero-originals/ (never committed):
 *   public/brand/hero/hero-N-desktop.jpg  1920 × 1080, at most 400 KB
 *   public/brand/hero/hero-N-mobile.jpg   1080 × 1350, at most 300 KB
 * Each photo is cropped around its focus point (scripts/hero-photos.json) and compressed until it
 * fits its size limit. Run: npm run hero:build
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'

import sharp from 'sharp'

import { focalCrop } from '../src/lib/media/crop'

type Focus = { fx: number; fy: number }
type Photo = { source: string; desktop: Focus; mobile: Focus }

const ROOT = process.cwd()
const ORIGINALS = path.join(ROOT, 'hero-originals')
const OUT = path.join(ROOT, 'public/brand/hero')
const SIZES = {
  desktop: { width: 1920, height: 1080, maxBytes: 400 * 1024 },
  mobile: { width: 1080, height: 1350, maxBytes: 300 * 1024 },
} as const

async function build(photo: Photo, n: number) {
  const file = path.join(ORIGINALS, photo.source)
  if (!existsSync(file)) throw new Error(`Missing original: hero-originals/${photo.source}`)
  const meta = await sharp(file).rotate().metadata()
  // After .rotate(), EXIF orientations 5–8 swap width and height.
  const swap = (meta.orientation ?? 1) >= 5
  const srcW = swap ? meta.height! : meta.width!
  const srcH = swap ? meta.width! : meta.height!
  for (const kind of ['desktop', 'mobile'] as const) {
    const size = SIZES[kind]
    if (srcW < size.width || srcH < size.height) {
      console.warn(
        `! ${photo.source} is ${srcW}×${srcH}: smaller than ${kind} (${size.width}×${size.height}), it will look soft`,
      )
    }
    const f = photo[kind]
    const c = focalCrop(srcW, srcH, size.width, size.height, f.fx, f.fy)
    const resized = sharp(file)
      .rotate()
      .extract({ left: c.sx, top: c.sy, width: c.sw, height: c.sh })
      .resize(size.width, size.height)
    let quality = 84
    let out = await resized.clone().jpeg({ quality, mozjpeg: true, progressive: true }).toBuffer()
    while (out.byteLength > size.maxBytes && quality > 40) {
      quality -= 4
      out = await resized.clone().jpeg({ quality, mozjpeg: true, progressive: true }).toBuffer()
    }
    if (out.byteLength > size.maxBytes) throw new Error(`${photo.source} ${kind} still too big`)
    const name = `hero-${n}-${kind}.jpg`
    await sharp(out).toFile(path.join(OUT, name))
    console.log(
      `${name}  ${(out.byteLength / 1024).toFixed(0)} KB  (quality ${quality}, crop ${c.sw}×${c.sh} at ${c.sx},${c.sy} of ${srcW}×${srcH})`,
    )
  }
}

async function main() {
  const { photos } = JSON.parse(
    readFileSync(path.join(ROOT, 'scripts/hero-photos.json'), 'utf8'),
  ) as {
    photos: Photo[]
  }
  mkdirSync(OUT, { recursive: true })
  // Start clean so a removed photo does not linger.
  for (const f of readdirSync(OUT))
    if (/^hero-\d+-(desktop|mobile)\.jpg$/.test(f)) rmSync(path.join(OUT, f))
  for (const [i, photo] of photos.entries()) await build(photo, i + 1)
  // The list the home page reads (in this order).
  const slides = photos.map((_, i) => ({
    desktop: `/brand/hero/hero-${i + 1}-desktop.jpg`,
    mobile: `/brand/hero/hero-${i + 1}-mobile.jpg`,
  }))
  writeFileSync(
    path.join(ROOT, 'src/config/heroSlides.ts'),
    `// Generated by \`npm run hero:build\` from scripts/hero-photos.json. Do not edit by hand.\n` +
      `import type { HeroSlide } from '@/components/landing/HeroBackdrop'\n\n` +
      `export const HERO_SLIDES: HeroSlide[] = ${JSON.stringify(slides, null, 2)}\n`,
  )
  console.log(`src/config/heroSlides.ts: ${slides.length} slides`)
}

void main()
